export function getBuilderWidget(
  type: string,
): BuilderWidgetDefinition | undefined {
  return BUILDER_WIDGETS.find(
    (widget) => widget.type === type,
  );
}

export function getBuilderWidgetsByCategory(
  category: string,
): BuilderWidgetDefinition[] {
  return BUILDER_WIDGETS.filter(
    (widget) => widget.category === category,
  );
}
